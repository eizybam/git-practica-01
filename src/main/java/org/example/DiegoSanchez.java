package org.example;

public class DiegoSanchez {
    public String nombre;
    public int edad;
    public String grupo;

    public void persona(){

    }

    public void persona(String nombre, int edad, String grupo){
        this.nombre = nombre;
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public int getEdad() {
        return edad;
    }

    public void setEdad(int edad) {
        this.edad = edad;
    }

    public String getGrupo() {
        return grupo;
    }

    public void setGrupo(String grupo) {
        this.grupo = grupo;
    }
}
